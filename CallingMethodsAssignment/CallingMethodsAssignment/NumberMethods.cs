using System;

namespace CallingMethodsAssignment
{
    public class NumberMethods
    {
        // This method multiplies the number by 2.
        public int Multiply(int number)
        {
            return number * 2;
        }

        // This method adds 20.
        public int AddTwenty(int number)
        {
            return number + 20;
        }

        // This method subtracts 5.
        public int SubtractFive(int number)
        {
            return number - 5;
        }
    }
}